def set_single_run(paragraph, text: str) -> None:
    if paragraph.runs:
        paragraph.runs[0].text = text
        for run in paragraph.runs[1:]:
            run.text = ""
    else:
        paragraph.add_run(text)


def set_abstract_paragraph(paragraph, label: str, content: str, colon: str = "：") -> None:
    if len(paragraph.runs) < 3:
        paragraph.clear()
        paragraph.add_run(label)
        paragraph.add_run(colon)
        paragraph.add_run(content)
    else:
        paragraph.runs[0].text = label
        paragraph.runs[1].text = colon
        paragraph.runs[2].text = content
        for run in paragraph.runs[3:]:
            run.text = ""


def set_keywords_paragraph(paragraph, label: str, content: str, english: bool = False) -> None:
    if english:
        if len(paragraph.runs) < 2:
            paragraph.clear()
            paragraph.add_run(f"{label}: ")
            paragraph.add_run(content)
        else:
            paragraph.runs[0].text = f"{label}: "
            paragraph.runs[1].text = content
            for run in paragraph.runs[2:]:
                run.text = ""
        return

    tokens = content.split("；")
    while len(paragraph.runs) < 2 + (len(tokens) * 2 - 1):
        paragraph.add_run("")
    paragraph.runs[0].text = label
    paragraph.runs[1].text = "："
    run_idx = 2
    for i, token in enumerate(tokens):
        paragraph.runs[run_idx].text = token
        run_idx += 1
        if i < len(tokens) - 1:
            paragraph.runs[run_idx].text = "；"
            run_idx += 1
    for run in paragraph.runs[run_idx:]:
        run.text = ""


def remove_paragraph(paragraph: Paragraph) -> None:
    element = paragraph._element
    parent = element.getparent()
    if parent is not None:
        parent.remove(element)


def insert_paragraph_after(paragraph: Paragraph, text: str = "", style: Optional[str] = None) -> Paragraph:
    new_p = OxmlElement("w:p")
    paragraph._p.addnext(new_p)
    new_para = Paragraph(new_p, paragraph._parent)
    if style:
        new_para.style = style
    if text:
        new_para.add_run(text)
    return new_para


def add_toc_field(paragraph: Paragraph) -> None:
    paragraph.alignment = 0
    fld_begin = OxmlElement("w:fldChar")
    fld_begin.set(qn("w:fldCharType"), "begin")

    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = ' TOC \\o "1-3" \\h \\z \\u '

    fld_sep = OxmlElement("w:fldChar")
    fld_sep.set(qn("w:fldCharType"), "separate")

    text = OxmlElement("w:t")
    text.text = "右键目录后选择“更新域”"

    text_run = OxmlElement("w:r")
    text_run.append(text)

    fld_end = OxmlElement("w:fldChar")
    fld_end.set(qn("w:fldCharType"), "end")

    for node in [fld_begin, instr, fld_sep, text_run, fld_end]:
        run = OxmlElement("w:r")
        if node.tag.endswith("t"):
            run.append(node)
            paragraph._p.append(run)
        elif node.tag.endswith("instrText"):
            run.append(node)
            paragraph._p.append(run)
        else:
            run.append(node)
            paragraph._p.append(run)


def insert_image_after(
    paragraph: Paragraph,
    image_name: str,
    caption: str,
    width_inches: float,
) -> Paragraph:
    image_path = Path(image_name)
    if not image_path.is_absolute():
        if image_name.startswith("screenshots/"):
            image_path = OUTPUT_DIR / image_name
        else:
            image_path = DIAGRAM_DIR / image_name
    image_paragraph = insert_paragraph_after(paragraph, "", "Normal")
    image_paragraph.alignment = 1
    image_paragraph.add_run().add_picture(str(image_path), width=Inches(width_inches))
    caption_paragraph = insert_paragraph_after(image_paragraph, caption, "Normal")
    caption_paragraph.alignment = 1
    return caption_paragraph


def insert_code_after(paragraph: Paragraph, code_text: str) -> Paragraph:
    code_paragraph = insert_paragraph_after(paragraph, "", "Normal")
    code_paragraph.paragraph_format.left_indent = Pt(18)
    code_paragraph.paragraph_format.right_indent = Pt(18)
    code_paragraph.paragraph_format.space_before = Pt(3)
    code_paragraph.paragraph_format.space_after = Pt(3)
    lines = code_text.strip("\n").splitlines()
    for index, line in enumerate(lines):
        run = code_paragraph.add_run(line)
        run.font.name = "Consolas"
        run._element.rPr.rFonts.set(qn("w:eastAsia"), "Consolas")
        run.font.size = Pt(9.5)
        run.font.color.rgb = RGBColor(60, 60, 60)
        if index < len(lines) - 1:
            run.add_break(WD_BREAK.LINE)
    return code_paragraph


def insert_table_after(
    paragraph: Paragraph,
    table_key: str,
    caption: str,
) -> Paragraph:
    definition = TABLE_DEFINITIONS[table_key]
    caption_paragraph = insert_paragraph_after(paragraph, caption, "Normal")
    caption_paragraph.alignment = 1

    table = caption_paragraph._parent.add_table(
        rows=1,
        cols=len(definition["headers"]),
        width=Inches(6.2),
    )
    caption_paragraph._p.addnext(table._tbl)
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER

    header_cells = table.rows[0].cells
    for index, header in enumerate(definition["headers"]):
        header_cells[index].text = header

    for row in definition["rows"]:
        cells = table.add_row().cells
        for index, value in enumerate(row):
            cells[index].text = value

    spacer_paragraph = insert_paragraph_after(caption_paragraph, "", "Normal")
    table._tbl.addnext(spacer_paragraph._p)
    return spacer_paragraph


def append_content(anchor: Paragraph, items: List[Tuple[str, str]]) -> Paragraph:
    current = anchor
    for kind, text in items:
        if kind == "chapter":
            current = insert_paragraph_after(current, text, "结语等(论文)")
            current.paragraph_format.page_break_before = True
        elif kind == "section":
            current = insert_paragraph_after(current, text, "节(论文)")
        elif kind == "subsection":
            current = insert_paragraph_after(current, text, "小节(论文)")
        elif kind == "image":
            image_name, caption, width_value = text.split("|")
            current = insert_image_after(current, image_name, caption, float(width_value))
        elif kind == "code":
            current = insert_code_after(current, text)
        elif kind == "table":
            table_key, caption = text.split("|", 1)
            current = insert_table_after(current, table_key, caption)
        else:
            current = insert_paragraph_after(current, text, "Normal")
    return current


